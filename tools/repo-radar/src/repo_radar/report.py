"""Markdown report generation."""
from .ranking import viral_score


def markdown_report(repos, language=None, days=7):
    lang_label = language or "all languages"
    lines = [
        "# 🔥 Repo Radar — Viral Repos",
        "",
        f"Fastest-growing new repositories on GitHub ({lang_label}, created in the last {days} days).",
        "",
        "| # | Repo | ⭐ Stars | 📈 Stars/day | Lang | Description |",
        "|---|------|---------|--------------|------|-------------|",
    ]
    for i, r in enumerate(repos, 1):
        desc = (r["description"] or "").replace("|", "\\|")[:80]
        score = viral_score(r)
        lines.append(
            f"| {i} | [{r['full_name']}]({r['url']}) | {r['stars']:,} | {score:.1f} | {r['language']} | {desc} |"
        )
    lines.append("")
    lines.append("_Generated by [Repo Radar](https://github.com/mehulpatel23b-pixel/repo-radar)._")
    return "\n".join(lines)
